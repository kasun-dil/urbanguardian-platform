import { serve } from "https://deno.land/std@0.168.0/http/server.ts";

const corsHeaders = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers": "authorization, x-client-info, apikey, content-type",
};

const systemPrompt = `You are UrbanPulse AI, a safety and disaster preparedness assistant for Sri Lanka. You ONLY answer questions related to:

1. **Safety Assessments**: Real-time safety information for travel and locations
2. **Weather Guidance**: Preparation tips for severe weather events like floods, cyclones, and monsoons
3. **Emergency Response**: Step-by-step guidance during disasters
4. **Disaster Preparedness**: How to prepare for emergencies
5. **Emergency Contacts**: Providing relevant contact numbers

Key emergency contacts in Sri Lanka:
- Emergency Services: 119 (24/7)
- Disaster Management: 117 (24/7)
- Police: 118 (24/7)
- Ambulance: 110 (24/7)

IMPORTANT: Do NOT answer questions unrelated to safety, disasters, or preparedness. If asked about unrelated topics, politely redirect the user by saying: "I'm specifically designed to help with safety and disaster preparedness. How can I assist you with those topics?"

Be concise, helpful, and prioritize user safety. When discussing emergencies, always remind users to contact official emergency services for immediate help.`;

serve(async (req) => {
  if (req.method === "OPTIONS") {
    return new Response(null, { headers: corsHeaders });
  }

  try {
    const { messages } = await req.json();
    const LOVABLE_API_KEY = Deno.env.get("LOVABLE_API_KEY");
    
    if (!LOVABLE_API_KEY) {
      throw new Error("LOVABLE_API_KEY is not configured");
    }

    const response = await fetch("https://ai.gateway.lovable.dev/v1/chat/completions", {
      method: "POST",
      headers: {
        Authorization: `Bearer ${LOVABLE_API_KEY}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        model: "google/gemini-3-flash-preview",
        messages: [
          { role: "system", content: systemPrompt },
          ...messages,
        ],
        stream: true,
      }),
    });

    if (!response.ok) {
      if (response.status === 429) {
        return new Response(JSON.stringify({ error: "Rate limit exceeded. Please try again later." }), {
          status: 429,
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }
      if (response.status === 402) {
        return new Response(JSON.stringify({ error: "Service temporarily unavailable." }), {
          status: 402,
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }
      const errorText = await response.text();
      console.error("AI gateway error:", response.status, errorText);
      return new Response(JSON.stringify({ error: "AI service error" }), {
        status: 500,
        headers: { ...corsHeaders, "Content-Type": "application/json" },
      });
    }

    return new Response(response.body, {
      headers: { ...corsHeaders, "Content-Type": "text/event-stream" },
    });
  } catch (e) {
    console.error("Chat error:", e);
    return new Response(JSON.stringify({ error: e instanceof Error ? e.message : "Unknown error" }), {
      status: 500,
      headers: { ...corsHeaders, "Content-Type": "application/json" },
    });
  }
});
